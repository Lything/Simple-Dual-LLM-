_SPACE_RE = re.compile(r"[\t\r\f\v ]+")
_SENTENCE_RE = re.compile(r"[^.!?\n]+(?:[.!?]+|$)", re.MULTILINE)
_PRICE_RE = re.compile(
    r"\$\s*(\d{1,3}(?:,\d{3})+(?:\.\d{1,2})?|\d+(?:\.\d{1,2})?)"
)
_SIZE_RE = re.compile(r"\b(Twin|Queen|King|Full|Single|Double)\b", re.I)


def normalise_text(text: str) -> str:
    """Normalise punctuation and whitespace for deterministic processing."""
    text = text.replace("\u2018", "'").replace("\u2019", "'")
    text = text.replace("\u201c", '"').replace("\u201d", '"')
    text = text.replace("\u2013", "-").replace("\u2014", "-")
    lines = [_SPACE_RE.sub(" ", line).strip() for line in text.splitlines()]
    return "\n".join(line for line in lines if line)


def sentence_spans(text: str) -> list[Span]:
    spans: list[Span] = []
    for match in _SENTENCE_RE.finditer(text):
        raw = match.group(0)
        left = len(raw) - len(raw.lstrip())
        cleaned = raw.strip()
        if cleaned:
            start = match.start() + left
            spans.append(Span(start, start + len(cleaned), cleaned))
    return spans


def _last_boundary(prefix: str) -> int:
    boundaries = [
        prefix.rfind(mark) + len(mark)
        for mark in (".", "!", "?", ",", ";", ":", "\n")
    ]
    low = prefix.lower()
    for token in (" but ", " however ", " whereas ", " while ", " instead "):
        pos = low.rfind(token)
        if pos >= 0:
            boundaries.append(pos + len(token))
    return max(boundaries, default=0)


def _claim_polarity(sentence: str, claim_start: int) -> str:
    """Determine polarity from the local clause preceding one extracted claim.

    The clause boundary prevents a leading response such as ``No, it uses ...``
    from negating the corrective statement after the comma.  It also separates
    ``official value, not incorrect value`` into positive and negative claims.
    """
    prefix = sentence[:claim_start]
    scope = prefix[_last_boundary(prefix):].lower()
    scope = re.sub(r"\bnot\s+only\b", "", scope)
    negation = re.search(
        r"\b(?:not|never|without)\b|\b(?:does|do|did|is|are|was|were|has|have|had)\s+not\b|"
        r"\b(?:doesn't|don't|didn't|isn't|aren't|wasn't|weren't|hasn't|haven't|hadn't)\b|"
        r"\brather\s+than\b",
        scope,
    )
    return "negative" if negation else "positive"


def _price_value(raw: str) -> int:
    return int(round(float(raw.replace(",", ""))))


def _price_display(value: int) -> str:
    return f"${value:,}"


def _name_matches(sentence: Span) -> list[tuple[int, int, str, str]]:
    matches: list[tuple[int, int, str, str]] = []
    for product_id, product in PRODUCTS.items():
        for alias in (product.name,) + product.name_aliases:
            match = re.search(re.escape(alias), sentence.text, re.I)
            if match:
                matches.append((match.start(), match.end(), product_id, match.group(0)))
                break
    return sorted(matches)


def _resolve_product(
    local_start: int,
    name_matches: list[tuple[int, int, str, str]],
    task: TaskSpecification,
) -> Optional[str]:
    preceding = [item for item in name_matches if item[0] <= local_start]
    if preceding:
        return preceding[-1][2]
    if len(task.product_ids) == 1:
        return task.product_ids[0]
    return None


def extract_propositions(text: str, task: TaskSpecification) -> list[Proposition]:
    propositions: list[Proposition] = []
    for sentence_index, sentence in enumerate(sentence_spans(text)):
        names = _name_matches(sentence)
        before_count = len(propositions)

        for local_start, local_end, product_id, raw in names:
            span = Span(sentence.start + local_start, sentence.start + local_end, raw)
            propositions.append(
                Proposition(
                    f"P{len(propositions)+1}", sentence_index, span, product_id,
                    "product_name", product_id, _claim_polarity(sentence.text, local_start),
                    "product_name",
                )
            )

        for concept_key, definition in CONCEPTS.items():
            seen: set[tuple[int, int]] = set()
            for pattern in definition.patterns:
                for match in re.finditer(pattern, sentence.text, re.I):
                    # A product name is verified separately; words such as
                    # "Memory Foam", "Spring" or "Latex" inside the name do
                    # not by themselves satisfy a feature requirement.
                    if any(
                        name_start < match.end() and match.start() < name_end
                        for name_start, name_end, _, _ in names
                    ):
                        continue
                    if any(
                        seen_start < match.end() and match.start() < seen_end
                        for seen_start, seen_end in seen
                    ):
                        continue
                    seen.add((match.start(), match.end()))
                    product_id = _resolve_product(match.start(), names, task)
                    span = Span(
                        sentence.start + match.start(), sentence.start + match.end(), match.group(0)
                    )
                    propositions.append(
                        Proposition(
                            f"P{len(propositions)+1}", sentence_index, span, product_id,
                            definition.attribute, concept_key,
                            _claim_polarity(sentence.text, match.start()), "concept",
                        )
                    )

        for match in _PRICE_RE.finditer(sentence.text):
            product_id = _resolve_product(match.start(), names, task)
            span = Span(sentence.start + match.start(), sentence.start + match.end(), match.group(0))
            propositions.append(
                Proposition(
                    f"P{len(propositions)+1}", sentence_index, span, product_id,
                    "price", _price_value(match.group(1)),
                    _claim_polarity(sentence.text, match.start()), "price",
                )
            )

        for match in _SIZE_RE.finditer(sentence.text):
            product_id = _resolve_product(match.start(), names, task)
            value = match.group(1).title()
            span = Span(sentence.start + match.start(), sentence.start + match.end(), match.group(0))
            propositions.append(
                Proposition(
                    f"P{len(propositions)+1}", sentence_index, span, product_id,
                    "sizes", value, _claim_polarity(sentence.text, match.start()), "size",
                )
            )

        if len(propositions) == before_count:
            propositions.append(
                Proposition(
                    f"P{len(propositions)+1}", sentence_index, sentence, None,
                    None, None, "positive", "none",
                )
            )
    return propositions


