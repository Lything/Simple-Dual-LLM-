def _authorised_concepts_for_attribute(product: ProductKnowledge, attribute: str) -> list[str]:
    return sorted(
        key
        for key in product.authorised_concepts
        if CONCEPTS[key].attribute == attribute
    )


def _concept_display(keys: Iterable[str]) -> list[str]:
    return [CONCEPTS[key].canonical for key in keys]


def _target_product(prop: Proposition, task: TaskSpecification) -> Optional[str]:
    if prop.product_id:
        return prop.product_id
    if len(task.product_ids) == 1:
        return task.product_ids[0]
    return None


def _record_for_proposition(
    prop: Proposition, task: TaskSpecification
) -> Optional[FactRecord]:
    product_id = _target_product(prop, task)
    if prop.value_kind == "none":
        return None

    if prop.value_kind == "product_name":
        result = "supported" if product_id in task.product_ids and prop.polarity == "positive" else "contradicted"
        official = PRODUCTS[product_id].name if product_id in PRODUCTS else None
        explanation = (
            "The product name is authorised for this task."
            if result == "supported"
            else "The product-name claim conflicts with the task and catalogue."
        )
        return FactRecord(
            product_id, prop.span.text, "product_name", prop.span.text, official,
            result, prop.polarity, [prop.span], explanation,
        )

    if product_id not in PRODUCTS:
        return FactRecord(
            product_id, prop.span.text, prop.attribute or "unknown", prop.value, None,
            "unsupported", prop.polarity, [prop.span],
            "The claim could not be mapped to a target product.",
        )

    product = PRODUCTS[product_id]

    if prop.value_kind == "concept":
        concept_key = str(prop.value)
        authorised = concept_key in product.authorised_concepts
        if prop.polarity == "positive":
            result = "supported" if authorised else "contradicted"
            explanation = (
                "The product feature is supported by the official catalogue."
                if authorised
                else "The positive product-feature claim conflicts with the official catalogue."
            )
        else:
            result = "contradicted" if authorised else "supported"
            explanation = (
                "The response incorrectly denies an authorised product feature."
                if authorised
                else "The response correctly rejects a feature that is not authorised for this product."
            )
        alternatives = _concept_display(
            _authorised_concepts_for_attribute(product, CONCEPTS[concept_key].attribute)
        )
        return FactRecord(
            product_id,
            prop.span.text,
            CONCEPTS[concept_key].attribute,
            CONCEPTS[concept_key].canonical,
            alternatives,
            result,
            prop.polarity,
            [prop.span],
            explanation,
        )

    if prop.value_kind == "price":
        authorised = int(prop.value) == product.price
        if prop.polarity == "positive":
            result = "supported" if authorised else "contradicted"
            explanation = (
                "The stated price matches the official catalogue."
                if authorised
                else "The stated price conflicts with the official catalogue."
            )
        else:
            result = "contradicted" if authorised else "supported"
            explanation = (
                "The response incorrectly denies the official price."
                if authorised
                else "The response correctly rejects an incorrect price."
            )
        return FactRecord(
            product_id, prop.span.text, "price", _price_display(int(prop.value)),
            _price_display(product.price), result, prop.polarity, [prop.span], explanation,
        )

    if prop.value_kind == "size":
        official_sizes = set(product.sizes)
        authorised = str(prop.value) in official_sizes
        if prop.polarity == "positive":
            result = "supported" if authorised else "contradicted"
            explanation = (
                "The stated size is officially available."
                if authorised
                else "The stated size is not officially available for this product."
            )
        else:
            result = "contradicted" if authorised else "supported"
            explanation = (
                "The response incorrectly denies an officially available size."
                if authorised
                else "The response correctly rejects an unavailable size."
            )
        return FactRecord(
            product_id, prop.span.text, "sizes", prop.value, list(product.sizes),
            result, prop.polarity, [prop.span], explanation,
        )
    return None


def _overlaps_existing(start: int, end: int, propositions: list[Proposition]) -> bool:
    return any(
        prop.span.start < end and start < prop.span.end
        for prop in propositions
        if prop.value_kind != "none"
    )


def _required_denial_satisfied(
    denial: RequiredDenial,
    product_id: str,
    propositions: list[Proposition],
    task: TaskSpecification,
) -> bool:
    for prop in propositions:
        if _target_product(prop, task) != product_id:
            continue
        if prop.polarity != "negative":
            continue
        if denial.kind == "concept" and prop.value_kind == "concept" and prop.value == denial.value:
            return True
        if denial.kind == "price" and prop.value_kind == "price" and prop.value == denial.value:
            return True
        if denial.kind == "size" and prop.value_kind == "size" and prop.value == denial.value:
            return True
    return False


def external_knowledge_check(
    text: str,
    propositions: list[Proposition],
    task: TaskSpecification,
) -> tuple[int, list[FactRecord]]:
    records: list[FactRecord] = []

    for prop in propositions:
        record = _record_for_proposition(prop, task)
        if record:
            records.append(record)

    # Detect generic fabricated claims not represented by catalogue concepts.
    for category, patterns in GENERIC_UNSUPPORTED_CLAIMS.items():
        for pattern in patterns:
            for match in re.finditer(pattern, text, re.I):
                if _overlaps_existing(match.start(), match.end(), propositions):
                    continue
                polarity = _claim_polarity(text, match.start())
                product_id = task.product_ids[0] if len(task.product_ids) == 1 else None
                result = "unsupported" if polarity == "positive" else "supported"
                records.append(
                    FactRecord(
                        product_id,
                        match.group(0),
                        category,
                        match.group(0),
                        None,
                        result,
                        polarity,
                        [Span(match.start(), match.end(), match.group(0))],
                        (
                            "The positive claim is not authorised by the official catalogue."
                            if result == "unsupported"
                            else "The response correctly rejects a claim absent from the catalogue."
                        ),
                    )
                )

    # Required catalogue product names (Q1).
    for product_id in task.require_product_names:
        found = any(
            prop.value_kind == "product_name"
            and prop.product_id == product_id
            and prop.polarity == "positive"
            for prop in propositions
        )
        if not found:
            records.append(
                FactRecord(
                    product_id, "", "product_name", None, PRODUCTS[product_id].name,
                    "omitted", "positive", [],
                    "The task requires this catalogue product name, but it is absent.",
                )
            )

    # Required feature groups: at least one authorised positive concept from
    # each group must be present.
    for product_id, groups in task.required_concept_groups.items():
        for group in groups:
            found = any(
                _target_product(prop, task) == product_id
                and prop.value_kind == "concept"
                and prop.polarity == "positive"
                and prop.value in group
                and prop.value in PRODUCTS[product_id].authorised_concepts
                for prop in propositions
            )
            if not found:
                records.append(
                    FactRecord(
                        product_id,
                        "",
                        CONCEPTS[group[0]].attribute,
                        None,
                        _concept_display(group),
                        "omitted",
                        "positive",
                        [],
                        "A task-required catalogue feature is absent from the response.",
                    )
                )

    # Required official price.
    for product_id in task.require_price:
        positive_price_claims = [
            prop
            for prop in propositions
            if _target_product(prop, task) == product_id
            and prop.value_kind == "price"
            and prop.polarity == "positive"
        ]
        found = any(
            _target_product(prop, task) == product_id
            and prop.value_kind == "price"
            and prop.polarity == "positive"
            and prop.value == PRODUCTS[product_id].price
            for prop in propositions
        )
        # An incorrect positive price is already classified as contradicted;
        # add omission only when no positive price was supplied at all.
        if not found and not positive_price_claims:
            records.append(
                FactRecord(
                    product_id, "", "price", None, _price_display(PRODUCTS[product_id].price),
                    "omitted", "positive", [],
                    "The task requires the official price, but it is absent.",
                )
            )

    # Tasks that ask for all sizes require exact positive coverage.  Correctly
    # denied unavailable sizes do not count as positive sizes.
    for product_id in task.require_exact_sizes:
        positive_sizes = {
            str(prop.value)
            for prop in propositions
            if _target_product(prop, task) == product_id
            and prop.value_kind == "size"
            and prop.polarity == "positive"
        }
        for missing in set(PRODUCTS[product_id].sizes) - positive_sizes:
            records.append(
                FactRecord(
                    product_id, "", "sizes", None, missing, "omitted", "positive", [],
                    f"The task requires the complete official size set; {missing} is absent.",
                )
            )

    # Misleading-premise questions require explicit correction of selected
    # false claims, not merely a generic 'No'.
    for product_id, denials in task.required_denials.items():
        for denial in denials:
            if not _required_denial_satisfied(denial, product_id, propositions, task):
                authorised_value: Any = denial.value
                if denial.kind == "concept":
                    authorised_value = f"explicit rejection of {CONCEPTS[str(denial.value)].canonical}"
                elif denial.kind == "price":
                    authorised_value = f"explicit rejection of {_price_display(int(denial.value))}"
                records.append(
                    FactRecord(
                        product_id,
                        "",
                        f"required_{denial.kind}_correction",
                        None,
                        authorised_value,
                        "omitted",
                        "negative",
                        [],
                        "The response does not explicitly correct one of the question's false premises.",
                    )
                )

    error_results = {"contradicted", "unsupported", "omitted"}
    factual_status = int(any(record.verification_result in error_results for record in records))
    return factual_status, records


