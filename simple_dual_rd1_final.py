def _safe_div(numerator: int, denominator: int) -> float:
    return numerator / denominator if denominator else 0.0


def _summarise_reports(reports: list[DetectionReport]) -> dict[str, Any]:
    def summarise(items: list[DetectionReport]) -> dict[str, Any]:
        total = len(items)
        detected = sum(report.overall_status for report in items)
        return {
            "records": total,
            "detected_responses": detected,
            "hallucination_free_responses": total - detected,
            "detection_rate": _safe_div(detected, total),
            "logical_detected_responses": sum(report.logical_status for report in items),
            "factual_detected_responses": sum(report.factual_status for report in items),
            "combined_detected_responses": sum(
                report.logical_status == 1 and report.factual_status == 1 for report in items
            ),
            "logical_events": sum(report.counts["logical_events"] for report in items),
            "supported_records": sum(report.counts["supported_records"] for report in items),
            "contradicted_records": sum(report.counts["contradicted_records"] for report in items),
            "unsupported_records": sum(report.counts["unsupported_records"] for report in items),
            "omitted_records": sum(report.counts["omitted_records"] for report in items),
        }

    model_ids = sorted({report.model_id for report in reports})
    task_ids = sorted({report.task_id for report in reports}, key=lambda value: int(value[1:]))
    return {
        "overall": summarise(reports),
        "by_model": {
            model_id: summarise([report for report in reports if report.model_id == model_id])
            for model_id in model_ids
        },
        "by_task": {
            task_id: summarise([report for report in reports if report.task_id == task_id])
            for task_id in task_ids
        },
    }


def validate_experimental_grid(
    reports: list[DetectionReport],
    model_ids: tuple[str, ...] = MODEL_IDS,
) -> dict[str, Any]:
    expected = {(task_id, model_id) for task_id in TASK_SPECIFICATIONS for model_id in model_ids}
    observed_pairs = [(report.task_id, report.model_id) for report in reports]
    observed = set(observed_pairs)
    duplicates = sorted({pair for pair in observed_pairs if observed_pairs.count(pair) > 1})
    missing = sorted(expected - observed, key=lambda pair: (int(pair[0][1:]), pair[1]))
    unexpected = sorted(observed - expected)
    return {
        "valid": not missing and not duplicates and not unexpected and len(reports) == 64,
        "expected_records": 64,
        "observed_records": len(reports),
        "missing_pairs": [list(pair) for pair in missing],
        "duplicate_pairs": [list(pair) for pair in duplicates],
        "unexpected_pairs": [list(pair) for pair in unexpected],
    }


def run_batch_csv(
    input_csv: Path,
    output_jsonl: Path,
    require_complete_grid: bool = False,
) -> dict[str, Any]:
    """Run automatic RD1 detection over CSV records.

    Required columns: ``task_id``, ``model_id`` and ``response``.
    The optional ``question`` column overrides the registered question text.
    Additional evaluation-label columns are neither required nor used.
    """
    reports: list[DetectionReport] = []
    with input_csv.open("r", encoding="gb18030", newline="") as handle:
        reader = csv.DictReader(handle)
        required_columns = {"task_id", "model_id", "response"}
        if not reader.fieldnames or not required_columns.issubset(reader.fieldnames):
            raise ValueError(
                f"CSV must contain columns {sorted(required_columns)}; got {reader.fieldnames}."
            )
        for row_number, row in enumerate(reader, start=2):
            task_id = (row.get("task_id") or "").strip().upper()
            model_id = (row.get("model_id") or "").strip()
            response = row.get("response") or ""
            if not task_id or not model_id:
                raise ValueError(f"Missing task_id or model_id on CSV row {row_number}.")
            reports.append(
                detect_hallucination(
                    task_id,
                    response,
                    model_id=model_id,
                    question=(row.get("question") or "").strip() or None,
                )
            )

    output_jsonl.parent.mkdir(parents=True, exist_ok=True)
    with output_jsonl.open("w", encoding="utf-8") as handle:
        for report in reports:
            handle.write(json.dumps(report.to_dict(), ensure_ascii=False) + "\n")

    grid = validate_experimental_grid(reports)
    if require_complete_grid and not grid["valid"]:
        raise ValueError(f"The batch is not the required complete 64-response grid: {grid}")
    return {
        "catalogue_version": CATALOGUE_VERSION,
        "output": str(output_jsonl),
        "grid_validation": grid,
        "automatic_summary": _summarise_reports(reports),
    }


def write_batch_template(output_csv: Path) -> None:
    """Write the fixed 64-row Q1-Q16 x four-model experiment template."""
    output_csv.parent.mkdir(parents=True, exist_ok=True)
    with output_csv.open("w", encoding="utf-8-sig", newline="") as handle:
        writer = csv.DictWriter(
            handle, fieldnames=["task_id", "model_id", "question", "response"]
        )
        writer.writeheader()
        for task_id, task in TASK_SPECIFICATIONS.items():
            for model_id in MODEL_IDS:
                writer.writerow(
                    {
                        "task_id": task_id,
                        "model_id": model_id,
                        "question": task.question,
                        "response": "",
                    }
                )


