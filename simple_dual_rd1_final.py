def _diagnostic_state(logical: int, factual: int) -> str:
    return {
        (0, 0): "no_detected_hallucination",
        (1, 0): "logical_hallucination_only",
        (0, 1): "factual_hallucination_only",
        (1, 1): "combined_logical_and_factual_hallucination",
    }[(logical, factual)]


def detect_hallucination(
    task_id: str,
    model_answer: str,
    model_id: str = "unknown-model",
    question: Optional[str] = None,
) -> DetectionReport:
    task_id = task_id.upper()
    if task_id not in TASK_SPECIFICATIONS:
        raise ValueError(f"Unknown task_id {task_id!r}; expected Q1-Q16.")
    task = TASK_SPECIFICATIONS[task_id]
    normalised = normalise_text(model_answer)
    propositions = extract_propositions(normalised, task)
    logical_status, logical_events = internal_self_consistency_check(propositions)
    factual_status, factual_records = external_knowledge_check(normalised, propositions, task)
    overall_status = int(bool(logical_status or factual_status))
    counts = {
        "logical_events": len(logical_events),
        "supported_records": sum(r.verification_result == "supported" for r in factual_records),
        "contradicted_records": sum(r.verification_result == "contradicted" for r in factual_records),
        "unsupported_records": sum(r.verification_result == "unsupported" for r in factual_records),
        "omitted_records": sum(r.verification_result == "omitted" for r in factual_records),
    }
    return DetectionReport(
        task_id,
        model_id,
        CATALOGUE_VERSION,
        question or task.question,
        normalised,
        propositions,
        logical_status,
        factual_status,
        overall_status,
        _diagnostic_state(logical_status, factual_status),
        logical_events,
        factual_records,
        counts,
    )


def print_report(report: DetectionReport, show_text: bool = True) -> None:
    print("===== Simple-Dual RD1 Detection Report =====")
    print(f"Task / Model: {report.task_id} / {report.model_id}")
    if show_text:
        print(f"Question: {report.question}")
        print(f"Response: {report.response}")
    print(f"Logical status: {report.logical_status}")
    for event in report.logical_events:
        print(f"  - [{event.rule_id}; {event.severity}] {event.explanation}")
    print(f"Factual status: {report.factual_status}")
    for record in report.factual_records:
        if record.verification_result != "supported":
            print(
                f"  - [{record.verification_result}] {record.product_id} / "
                f"{record.attribute}: {record.explanation}"
            )
    print(f"Overall status: {report.overall_status} ({report.diagnostic_state})")


