MUTUAL_EXCLUSION_RULES: tuple[tuple[str, str, str], ...] = (
    ("L-STRUCT-01", "memory_foam", "inner_spring"),
    ("L-MATERIAL-01", "memory_foam", "natural_latex"),
    ("L-COOL-01", "cooling_gel", "heat_retaining_foam"),
    ("L-COVER-01", "silver_thread", "unembroidered_cover"),
    ("L-BASE-01", "high_density_foam_base", "thin_disposable_base"),
)


def internal_self_consistency_check(
    propositions: list[Proposition],
) -> tuple[int, list[LogicalEvent]]:
    events: list[LogicalEvent] = []
    positive_concepts = [
        prop for prop in propositions
        if prop.value_kind == "concept" and prop.polarity == "positive"
    ]

    for rule_id, left_key, right_key in MUTUAL_EXCLUSION_RULES:
        left = [prop for prop in positive_concepts if prop.value == left_key]
        right = [prop for prop in positive_concepts if prop.value == right_key]
        for left_prop in left:
            for right_prop in right:
                same_product = (
                    left_prop.product_id == right_prop.product_id
                    or left_prop.product_id is None
                    or right_prop.product_id is None
                )
                if same_product:
                    events.append(
                        LogicalEvent(
                            rule_id,
                            "mutually_exclusive_claims",
                            "high",
                            f"'{left_prop.span.text}' conflicts with '{right_prop.span.text}'.",
                            [left_prop.span, right_prop.span],
                        )
                    )
                    break

    # A response cannot assert two different positive prices for one product.
    product_ids = {prop.product_id for prop in propositions if prop.product_id}
    for product_id in product_ids:
        prices = [
            prop for prop in propositions
            if prop.product_id == product_id
            and prop.value_kind == "price"
            and prop.polarity == "positive"
        ]
        values = {prop.value for prop in prices}
        if len(values) > 1:
            events.append(
                LogicalEvent(
                    "L-VALUE-PRICE",
                    "inconsistent_attribute_values",
                    "high",
                    f"Multiple positive prices were asserted for {product_id}: "
                    f"{[_price_display(value) for value in sorted(values)]}.",
                    [prop.span for prop in prices],
                )
            )

    # The same exact claim cannot be both affirmed and denied.
    keyed: dict[tuple[Optional[str], str, str], list[Proposition]] = {}
    for prop in propositions:
        if prop.value_kind in {"concept", "price", "size", "product_name"}:
            keyed.setdefault((prop.product_id, prop.value_kind, str(prop.value)), []).append(prop)
    for (product_id, kind, value), claims in keyed.items():
        if {claim.polarity for claim in claims} == {"positive", "negative"}:
            events.append(
                LogicalEvent(
                    f"L-POLARITY-{kind.upper()}",
                    "contradictory_polarity",
                    "high",
                    f"The response both affirms and denies {kind}={value} for {product_id}.",
                    [claim.span for claim in claims],
                )
            )

    return int(bool(events)), events


