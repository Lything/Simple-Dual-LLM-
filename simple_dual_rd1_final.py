def run_self_test() -> dict[str, Any]:
    failures: list[str] = []
    reference_results: dict[str, dict[str, int]] = {}
    for task_id, answer in STANDARD_REFERENCE_ANSWERS.items():
        report = detect_hallucination(task_id, answer, model_id="reference-answer")
        reference_results[task_id] = {
            "logical_status": report.logical_status,
            "factual_status": report.factual_status,
            "overall_status": report.overall_status,
        }
        if report.overall_status != 0:
            failures.append(f"{task_id} reference answer was not accepted: {report.to_dict()}")

    targeted_cases = {
        "correct_negation": (
            "Q4",
            "No. It uses memory foam and does not contain an inner-spring construction. "
            "Its official price is $999, not $1,299.",
            0,
        ),
        "logical_conflict": (
            "Q1",
            "It uses memory foam and an inner-spring construction, with a high-density "
            "foam base, cooling gel, a breathable hypoallergenic cover, and silver threads.",
            1,
        ),
        "wrong_product2_price": (
            "Q7", "Its official price is $999, and it is available in Queen and King sizes.", 1
        ),
        "incomplete_product1_sizes": (
            "Q3", "Its official price is $999, and it is available in Twin and Queen sizes.", 1
        ),
    }
    targeted_results: dict[str, int] = {}
    for name, (task_id, answer, expected_overall) in targeted_cases.items():
        report = detect_hallucination(task_id, answer, model_id="self-test")
        targeted_results[name] = report.overall_status
        if report.overall_status != expected_overall:
            failures.append(
                f"{name} expected overall={expected_overall}, got {report.overall_status}: "
                f"{report.to_dict()}"
            )

    return {
        "passed": not failures,
        "reference_answers_tested": len(reference_results),
        "reference_results": reference_results,
        "targeted_results": targeted_results,
        "failures": failures,
    }


def run_reference_answer_evaluation(
    print_details: bool = True,
    print_summary: bool = True,
) -> tuple[list[DetectionReport], dict[str, Any]]:
    """Evaluate and optionally display all sixteen standard reference answers."""
    reports: list[DetectionReport] = []
    if print_details:
        print("\n===== Q1-Q16 Standard Reference Answer Evaluation =====")
    for index, task_id in enumerate(TASK_SPECIFICATIONS, start=1):
        report = detect_hallucination(
            task_id,
            STANDARD_REFERENCE_ANSWERS[task_id],
            model_id="standard-reference-answer",
        )
        reports.append(report)
        if print_details:
            print(f"\n----- Reference answer {index}/16 -----")
            print_report(report, show_text=True)

    summary = _summarise_reports(reports)["overall"]
    if print_summary:
        print("\n===== Q1-Q16 Reference Evaluation Summary =====")
        print(f"Total questions: {summary['records']}")
        print(f"Hallucination-free answers: {summary['hallucination_free_responses']}")
        print(f"Detected answers: {summary['detected_responses']}")
        print(f"Logical detected answers: {summary['logical_detected_responses']}")
        print(f"Factual detected answers: {summary['factual_detected_responses']}")
        print(f"Overall detection rate: {summary['detection_rate']:.4f}")
    return reports, summary


def _read_answer_argument(answer: Optional[str], answer_file: Optional[Path]) -> str:
    if answer_file is not None:
        if not answer_file.exists():
            raise FileNotFoundError(f"Answer file does not exist: {answer_file}")
        return answer_file.read_text(encoding="utf-8-sig").strip()
    if answer is not None:
        return answer.strip()
    raise ValueError("A model answer must be supplied with --answer or --answer-file.")


def run_pycharm_mode() -> None:
    """Run the selected top-level configuration without command-line arguments.

    This entry point is intended for the normal PyCharm workflow: edit the
    ``PYCHARM_*`` constants near the top of this file and click Run.
    """
    mode = PYCHARM_MODE.strip().upper()

    if mode == "REFERENCE_16":
        run_reference_answer_evaluation(print_details=True, print_summary=True)
        return

    if mode == "SINGLE":
        configured_file = PYCHARM_ANSWER_FILE.strip()
        answer_file = Path(configured_file).expanduser() if configured_file else None
        answer = _read_answer_argument(PYCHARM_MODEL_ANSWER, answer_file)
        if not answer:
            raise ValueError(
                "PYCHARM_MODEL_ANSWER is empty. Paste the generated model answer "
                "between the triple quotes, or configure PYCHARM_ANSWER_FILE."
            )
        report = detect_hallucination(
            PYCHARM_TASK_ID,
            answer,
            model_id=PYCHARM_MODEL_ID,
        )
        print_report(report, show_text=True)
        return

    if mode == "CREATE_TEMPLATE":
        template_path = Path(PYCHARM_TEMPLATE_PATH).expanduser()
        write_batch_template(template_path)
        print("\n===== Simple-Dual RD1 CSV Template Created =====")
        print(f"File: {template_path.resolve()}")
        print("Rows: 64 (Q1-Q16 x four models)")
        return

    if mode == "BATCH":
        batch_path = Path(PYCHARM_BATCH_CSV_PATH).expanduser()
        output_path = Path(PYCHARM_BATCH_OUTPUT_PATH).expanduser()
        summary = run_batch_csv(
            batch_path,
            output_path,
            require_complete_grid=PYCHARM_REQUIRE_COMPLETE_GRID,
        )
        print("\n===== Simple-Dual RD1 Batch Summary =====")
        print(json.dumps(summary, ensure_ascii=False, indent=2))
        return

    if mode == "SELF_TEST":
        result = run_self_test()
        print("\n===== Simple-Dual RD1 Self-Test =====")
        print(json.dumps(result, ensure_ascii=False, indent=2))
        if not result["passed"]:
            raise AssertionError("Simple-Dual self-test failed; see failures above.")
        return

    allowed_modes = "REFERENCE_16, SINGLE, CREATE_TEMPLATE, BATCH, SELF_TEST"
    raise ValueError(
        f"Unknown PYCHARM_MODE: {PYCHARM_MODE!r}. Choose one of: {allowed_modes}."
    )


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Simple-Dual final RD1 single-turn hallucination detector"
    )
    parser.add_argument("--batch-csv", type=Path, help="Run a Q1-Q16 response CSV")
    parser.add_argument(
        "--output", type=Path, default=Path("simple_dual_rd1_results.jsonl")
    )
    parser.add_argument(
        "--require-complete-grid",
        action="store_true",
        help="Require exactly one response for every Q1-Q16 x four-model pair",
    )
    parser.add_argument("--write-template", type=Path, help="Write the 64-row CSV template")
    parser.add_argument("--self-test", action="store_true", help="Run deterministic tests")
    parser.add_argument(
        "--reference-test",
        action="store_true",
        help="Display detection results for all Q1-Q16 standard answers",
    )
    parser.add_argument(
        "--task-id",
        type=str,
        help="Evaluate one generated answer using Q1-Q16, for example Q4",
    )
    answer_group = parser.add_mutually_exclusive_group()
    answer_group.add_argument("--answer", type=str, help="Generated answer text")
    answer_group.add_argument(
        "--answer-file",
        type=Path,
        help="UTF-8 text file containing one generated answer",
    )
    parser.add_argument(
        "--model-id",
        type=str,
        default="unknown-model",
        help="Model name recorded in a single-answer report",
    )
    parser.add_argument(
        "--question",
        type=str,
        help="Optional question override for a single-answer report",
    )
    parser.add_argument("--json", action="store_true", help="Print machine-readable JSON")
    args = parser.parse_args()

    if args.write_template:
        write_batch_template(args.write_template)
        print(json.dumps({"template": str(args.write_template), "records": 64}, indent=2))
        return
    if args.self_test:
        result = run_self_test()
        print(json.dumps(result, ensure_ascii=False, indent=2))
        raise SystemExit(0 if result["passed"] else 1)
    if args.batch_csv:
        summary = run_batch_csv(
            args.batch_csv, args.output, require_complete_grid=args.require_complete_grid
        )
        print(json.dumps(summary, ensure_ascii=False, indent=2))
        return
    if args.task_id:
        answer = _read_answer_argument(args.answer, args.answer_file)
        report = detect_hallucination(
            args.task_id,
            answer,
            model_id=args.model_id,
            question=args.question,
        )
        if args.json:
            print(json.dumps(report.to_dict(), ensure_ascii=False, indent=2))
        else:
            print_report(report, show_text=True)
        return
    if args.answer is not None or args.answer_file is not None:
        parser.error("--answer and --answer-file require --task-id Q1-Q16")

    # With no arguments, show the complete Q1-Q16 standard-answer evaluation.
    reports, summary = run_reference_answer_evaluation(
        print_details=not args.json,
        print_summary=not args.json,
    )
    if args.json:
        print(
            json.dumps(
                {
                    "reports": [report.to_dict() for report in reports],
                    "summary": summary,
                },
                ensure_ascii=False,
                indent=2,
            )
        )


if __name__ == "__main__":
    # PyCharm's green Run button normally starts the file without arguments.
    # Explicit command-line arguments continue to use the original CLI.
    if len(sys.argv) == 1:
        run_pycharm_mode()
    else:
        main()
